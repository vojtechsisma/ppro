-- V1: Výchozí schéma půjčovny Hory a voda.
-- Výčtové typy jsou uloženy jako VARCHAR s CHECK omezením (přenositelné mezi PostgreSQL a testovací H2).

-- 1. Uživatelé systému (personál půjčovny)
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL,
    email           VARCHAR(100) NOT NULL,
    hashed_password VARCHAR(255) NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    is_active       BOOLEAN      NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'STAFF'))
);

-- 2. Kategorie vybavení (číselník s ceníkem)
CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)   NOT NULL,
    code            VARCHAR(20)    NOT NULL,
    description     VARCHAR(1000),
    base_daily_rate NUMERIC(10, 2) NOT NULL,
    weekend_rate    NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uq_categories_name UNIQUE (name),
    CONSTRAINT uq_categories_code UNIQUE (code)
);

-- 3. Konkrétní fyzické kusy vybavení
CREATE TABLE equipment_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id      BIGINT       NOT NULL,
    inventory_number VARCHAR(50)  NOT NULL,
    model_name       VARCHAR(100) NOT NULL,
    size             VARCHAR(30)  NOT NULL,
    year_acquired    INTEGER      NOT NULL,
    wear_condition   VARCHAR(20)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uq_equipment_items_inventory_number UNIQUE (inventory_number),
    CONSTRAINT fk_equipment_items_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_equipment_items_wear_condition CHECK (wear_condition IN ('NEW', 'EXCELLENT', 'GOOD', 'FAIR', 'DAMAGED')),
    CONSTRAINT ck_equipment_items_status CHECK (status IN ('AVAILABLE', 'RENTED', 'IN_SERVICE', 'RETIRED'))
);
CREATE INDEX ix_equipment_items_status ON equipment_items (status);

-- 4. Zákazníci
CREATE TABLE customers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         VARCHAR(50) NOT NULL,
    last_name          VARCHAR(50) NOT NULL,
    phone              VARCHAR(20) NOT NULL,
    id_document_number VARCHAR(30) NOT NULL,
    created_at         TIMESTAMP   NOT NULL,
    CONSTRAINT uq_customers_id_document_number UNIQUE (id_document_number)
);
CREATE INDEX ix_customers_last_name ON customers (last_name);
CREATE INDEX ix_customers_phone ON customers (phone);

-- 5. Výpůjčky
CREATE TABLE rentals (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT         NOT NULL,
    planned_start   TIMESTAMP      NOT NULL,
    planned_end     TIMESTAMP      NOT NULL,
    deposit_amount  NUMERIC(10, 2) NOT NULL,
    discount_amount NUMERIC(10, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    CONSTRAINT fk_rentals_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_rentals_status CHECK (status IN ('ACTIVE', 'RETURNED_PARTIAL', 'COMPLETED', 'OVERDUE', 'CANCELLED'))
);
CREATE INDEX ix_rentals_status ON rentals (status);

-- 6. Položky výpůjčky (vazební entita M:N Rental <-> EquipmentItem se snapshotem ceny)
CREATE TABLE rental_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id          BIGINT         NOT NULL,
    equipment_item_id  BIGINT         NOT NULL,
    unit_daily_price   NUMERIC(10, 2) NOT NULL,
    actual_returned_at TIMESTAMP,
    late_fee           NUMERIC(10, 2) NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    damage_notes       VARCHAR(2000),
    CONSTRAINT fk_rental_items_rental FOREIGN KEY (rental_id) REFERENCES rentals (id) ON DELETE CASCADE,
    CONSTRAINT fk_rental_items_equipment_item FOREIGN KEY (equipment_item_id) REFERENCES equipment_items (id) ON DELETE RESTRICT,
    CONSTRAINT ck_rental_items_status CHECK (status IN ('RENTED', 'RETURNED', 'DAMAGED'))
);
CREATE INDEX ix_rental_items_rental_id ON rental_items (rental_id);
CREATE INDEX ix_rental_items_equipment_item_id ON rental_items (equipment_item_id);
