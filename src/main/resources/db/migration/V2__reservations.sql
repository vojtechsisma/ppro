-- Rezervace typu: zákazník po telefonu chce „lyže 170“, ne konkrétní kus.
-- Rezervace drží kapacitu kategorie a velikosti; konkrétní kusy se přiřadí až při výdeji,
-- kdy z rezervace vznikne výpůjčka (rental_id).
CREATE TABLE reservations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT         NOT NULL,
    category_id      BIGINT         NOT NULL,
    size             VARCHAR(30)    NOT NULL,
    quantity         INTEGER        NOT NULL,
    planned_start    TIMESTAMP      NOT NULL,
    planned_end      TIMESTAMP      NOT NULL,
    pickup_deadline  TIMESTAMP      NOT NULL,
    unit_daily_price NUMERIC(10, 2) NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    rental_id        BIGINT,
    created_at       TIMESTAMP      NOT NULL,
    CONSTRAINT fk_reservations_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_rental FOREIGN KEY (rental_id) REFERENCES rentals (id) ON DELETE RESTRICT,
    CONSTRAINT ck_reservations_quantity CHECK (quantity BETWEEN 1 AND 20),
    CONSTRAINT ck_reservations_term CHECK (planned_end > planned_start),
    CONSTRAINT ck_reservations_status CHECK (status IN ('ACTIVE', 'FULFILLED', 'EXPIRED', 'CANCELLED'))
);
CREATE INDEX ix_reservations_status ON reservations (status);
CREATE INDEX ix_reservations_category_size ON reservations (category_id, size);
